#!/usr/bin/env python3
"""Fail when a credential is committed, or when a committed file looks like it should not be.

    python3 scripts/scan-secrets.py [--all] [--quiet]

Two different failures, both worth blocking a merge over:

1. **A secret in the tree.** Provider keys, private keys, JWTs, credentials in a URL. The patterns here
   are specific enough to be actionable — a scanner that flags every 32-character string teaches people
   to ignore it, which is the same as not having one.
2. **A file that should never be committed at all.** `.env` with values, key material, database dumps.
   Checked by path, because the content of a real `.env` is exactly what a secret scan is for.

Standard library only, no network: CI can run it on every push, and so can you before you commit.
Exit code 1 means "do not merge".

Suppressing a finding is deliberate and visible: put `scan: allow <reason>` on the offending line or the
line above it. The reason is mandatory, because "we decided this is fine" is the only thing a future
reader needs and the only thing they cannot reconstruct.
"""

import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]

# Files whose content is not ours to police: lockfiles are hashes, and the two vendored bundles are
# generated by tools. Everything else in the tree is read.
SKIP_CONTENT = {
    "package-lock.json",
    "npm-shrinkwrap.json",
    "go.sum",
}

SKIP_DIRS = {
    "node_modules",
    ".git",
    ".next",
    "dist",
    "build",
    "coverage",
    "__pycache__",
    ".venv",
    "vendor",
}

# Path shapes that should never be tracked, whatever they contain.
FORBIDDEN_PATHS = [
    (re.compile(r"(^|/)\.env$"), "a real .env holds live credentials; .env.example is tracked instead"),
    (re.compile(r"(^|/)\.env\.(?!example)[a-z]+$"), "environment file with values"),
    (re.compile(r"\.(pem|key|p12|pfx|jks|keystore)$"), "key material"),
    (re.compile(r"(^|/)id_(rsa|dsa|ecdsa|ed25519)$"), "an SSH private key"),
    (re.compile(r"(^|/)\.npmrc$"), "may contain an auth token"),
    (re.compile(r"(^|/)\.netrc$"), "may contain credentials"),
    (re.compile(r"\.(db|sqlite|sqlite3)(-wal|-shm)?$"), "a database file, not source"),
    (re.compile(r"\.(dump|sql\.gz|bak)$"), "a database dump"),
]

# Each pattern is (name, regex, what to do about it). Order matters only for readability of output.
PATTERNS = [
    ("private key block", re.compile(r"-----BEGIN (?:RSA |EC |DSA |OPENSSH |PGP )?PRIVATE KEY-----"),
     "remove the key and rotate it; history keeps whatever was pushed"),
    ("AWS access key id", re.compile(r"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b"),
     "rotate the key pair in IAM"),
    ("GitHub token", re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{36,}\b"),
     "revoke the token in GitHub settings"),
    ("GitHub fine-grained token", re.compile(r"\bgithub_pat_[A-Za-z0-9_]{40,}\b"),
     "revoke the token in GitHub settings"),
    ("Stripe live key", re.compile(r"\b(?:sk|rk)_live_[A-Za-z0-9]{20,}\b"),
     "this is a live payment credential: rotate it now"),
    ("Paystack secret key", re.compile(r"\bsk_live_[0-9a-f]{32,}\b"), "rotate the key in the dashboard"),
    ("Slack token", re.compile(r"\bxox[baprs]-[A-Za-z0-9-]{10,}\b"), "revoke the token"),
    ("Google API key", re.compile(r"\bAIza[0-9A-Za-z_-]{35}\b"), "restrict or rotate the key"),
    ("SendGrid / SMTP key", re.compile(r"\bSG\.[A-Za-z0-9_-]{16,}\.[A-Za-z0-9_-]{16,}\b"), "rotate the key"),
    ("JWT", re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b"),
     "a signed token in the tree is a live session; revoke it"),
    # Credentials embedded in a URL are the most common leak in application code, and the easiest to
    # overlook because the line looks like ordinary configuration.
    ("credentials in a URL",
     re.compile(r"\b[A-Za-z][A-Za-z0-9+.-]*://[^/\s:@]+:[^/\s:@]{3,}@[^\s/:'\"]*"),
     "move the credential to an environment variable"),
    # A literal assignment to something called a secret with a value long enough to be one. The length
    # floor is what keeps this from flagging `secret = "change_me"` in documentation.
    ("assigned secret", re.compile(
        r"(?i)\b(?:api[_-]?key|secret[_-]?key|access[_-]?token|client[_-]?secret|"
        r"private[_-]?key|auth[_-]?token)\b\s*[:=]\s*[\"'][A-Za-z0-9_\-/+=]{20,}[\"']"),
     "read it from the environment instead"),
]

ALLOW_MARKER = re.compile(r"scan:\s*allow\b")

# A password for your own laptop is not a leak. Local development defaults — a trust-auth socket, a
# throwaway compose database, a placeholder that says "change me" — are what documentation and CI need in
# order to work at all, and flagging them teaches people to ignore the scanner. Anywhere else, a
# credential in a URL is exactly the leak this rule exists for.
LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1", "0.0.0.0", "host.docker.internal"}
PLACEHOLDER_FRAGMENTS = ("change_me", "change-me", "local_only", "example", "placeholder", "your_",
                         "xxxx", "dummy", "password", "secret")


# Named exceptions, keyed by file, with the reason written here rather than as a comment in the file —
# so an exception is reviewable in one place and cannot be quietly widened by editing code.
ALLOWED_LINES = {
    # A published npm integrity hash is public by design; it is a check value, not a credential.
    "apps/mobile/package-lock.json": {"integrity"},
}


def is_local_development_credential(url):
    """True for a URL credential that cannot grant access to anything but a development machine."""
    try:
        parts = urlsplit(url)
        password = parts.password or ""
        host = parts.hostname or ""
    except ValueError:
        return False
    if any(fragment in password.lower() for fragment in PLACEHOLDER_FRAGMENTS):
        return True
    return host in LOCAL_HOSTS or host.startswith("127.")


def tracked_files():
    """Every file git knows about. Untracked scratch files cannot leak, so they are not the subject."""
    try:
        out = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files", "-z"],
            check=True, capture_output=True, text=True,
        ).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        # No git (a tarball export, say): fall back to walking, which is stricter rather than looser.
        return [str(p.relative_to(ROOT)) for p in ROOT.rglob("*") if p.is_file()]
    return [name for name in out.split("\0") if name]


def is_skipped(path):
    return any(part in SKIP_DIRS for part in Path(path).parts)


def scan(path):
    """Return findings for one file as (line number, kind, remedy, excerpt)."""
    try:
        text = (ROOT / path).read_text(encoding="utf-8", errors="replace")
    except (OSError, UnicodeError):
        return []
    if "\x00" in text[:4096]:  # binary: not a place a credential is written
        return []
    return scan_text(path, text)


def scan_text(path, text):
    """Apply the patterns to a file's contents. Separated from the filesystem so the detector itself
    can be tested — a scanner that has never been shown a secret is a scanner nobody should trust."""
    findings = []
    lines = text.splitlines()
    allowed = ALLOWED_LINES.get(path, set())
    for number, line in enumerate(lines, start=1):
        if ALLOW_MARKER.search(line) or (number > 1 and ALLOW_MARKER.search(lines[number - 2])):
            continue
        if any(token in line for token in allowed):
            continue
        for kind, pattern, remedy in PATTERNS:
            match = pattern.search(line)
            if not match:
                continue
            if kind == "credentials in a URL" and is_local_development_credential(match.group(0)):
                continue
            findings.append((number, kind, remedy, redact(line, match)))
            break  # one finding per line is enough to act on
    return findings


def redact(line, match):
    """Show enough of the line to find it, not enough to use what was found."""
    value = match.group(0)
    if len(value) > 8:
        masked = value[:4] + "…" + value[-2:]
    else:
        masked = "…"
    return line.replace(value, masked).strip()[:160]


# Fixtures for --self-test. These are not credentials: they are shapes that must be caught, and shapes
# that must not be. A scanner is only worth its noise if both halves are asserted.
SELF_TEST_CASES = [
    ("aws = AKIAIOSFODNN7EXAMPLE", True),
    ("token: ghp_" + "a" * 36, True),
    ("-----BEGIN RSA PRIVATE KEY-----", True),
    ("key = sk_live_" + "b" * 24, True),
    ("slack = xoxb-123456789012-abcdefghijkl", True),
    ("hook: https://user:hunter2@hooks.prod.example.com/x", True),
    ('client_secret = "s3cr3tvalue_thats_long_enough"', True),
    ("jwt = eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.dBjftJeZ4CVPmB92K27uhbUJU1p1r_wW1gFWFOEjXk", True),
    # The development defaults this repository depends on: same shape, no reach.
    ("EDUMART_DSN=postgres://edumart:local_only_change_me@localhost:5432/edumart?sslmode=disable", False),
    ("EDUMART_TEST_POSTGRES_DSN: postgres://edumart:edumart@localhost:5432/edumart_test?sslmode=disable", False),
    ('EDUMART_SMTP_PASSWORD=change_me', False),
    ('password = "Student123!"', False),
    ("# rotate the EDUMART_WEBHOOK_SECRET per environment", False),
    ('{"email": "student@edumart.ng"}', False),
]


def self_test():
    failures = 0
    for text, should_find in SELF_TEST_CASES:
        found = bool(scan_text("selftest", text))
        if found != should_find:
            print(f"FAIL: {'missed' if should_find else 'false positive'}: {text[:70]}")
            failures += 1
    if failures:
        print(f"\n{failures} self-test case(s) failed: the detector is not doing what it claims.",
              file=sys.stderr)
        return 1
    print(f"self-test passed: {len(SELF_TEST_CASES)} cases, secrets caught and local defaults left alone")
    return 0


def main(argv):
    if "--self-test" in argv:
        return self_test()
    quiet = "--quiet" in argv
    paths = tracked_files()
    problems = 0

    for path in paths:
        for pattern, reason in FORBIDDEN_PATHS:
            if pattern.search(path):
                print(f"{path}: this file should not be tracked — {reason}")
                problems += 1
                break

    for path in paths:
        name = Path(path).name
        if name in SKIP_CONTENT or is_skipped(path):
            continue
        for number, kind, remedy, excerpt in scan(path):
            print(f"{path}:{number}: {kind} — {remedy}")
            if not quiet:
                print(f"    {excerpt}")
            problems += 1

    if problems:
        print(f"\n{problems} finding(s). A committed secret is not fixed by deleting it: rotate it, then "
              f"remove it from history.", file=sys.stderr)
        return 1
    print(f"no secrets found in {len(paths)} tracked file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
